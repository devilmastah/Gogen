// Package steerq is the FIFO of turns waiting for a busy session to go idle.
//
// The web host and the TUI each keep one queue per session and drain it at the
// session's idle boundary. The queue itself — its three item kinds, the two
// caps, the eviction rules, the batching rule (Batch: notice runs, joined user
// runs under join_queued and their image cap, Join), the Send now rule
// (CheckSendNow), and the "zero the popped slots" requirement — used to be
// implemented twice (internal/server/deliver.go
// and internal/tui/steering.go), so every fix had to be made twice and the two
// copies had already drifted in how they expressed the same policy. This
// package owns it once; each host keeps its own drain machinery, because that
// part is genuinely transport-specific (a goroutine worker over a WebSocket vs
// a tea.Cmd on the Update thread).
//
// Queue is NOT goroutine-safe by design: the web host guards its queue with the
// runtime's deliverMu (its drain, eviction and orphan-check paths take that lock
// explicitly, and their lock ordering with the turn lock is part of the
// delivery state machine), while the TUI's queue lives entirely on the Update
// thread. Moving the lock in here would nest it under/over those, so the host
// keeps its own.
package steerq

import (
	"strings"

	"gogen/internal/llm"
)

// Kind classifies a queued item. It decides both presentation and policy.
type Kind int

const (
	// Notice is a machine-generated one-way message (job completion notice,
	// scheduled reminder, subagent terminal event). Notices are the only
	// items that are (a) dropped oldest-first when the system cap is
	// reached and (b) batched: a contiguous run of notices at the head of
	// the queue is delivered as ONE turn, because each one is a provider
	// request nobody waits on.
	Notice Kind = iota
	// Reply is a TARGETED delivery whose exact turn output is the answer
	// somebody is waiting for (a send_message into a subagent). It gets its
	// own turn — the reply capture is armed per turn and must stay 1:1 with
	// the call — and it is NEVER the eviction victim, so a queue full of
	// replies drops an arriving notice instead of a pending answer.
	Reply
	// User is text the user typed into a busy session. It runs as its own
	// turn, or joined with the User items behind it when join_queued is on
	// (see Batch). It is never silently dropped: reaching the cap REFUSES
	// the enqueue so the host can tell the user.
	User
)

// Item is one queued turn waiting for the session to go idle.
type Item struct {
	// ID identifies the item (host-side cancel targeting, and the client's
	// queued-bubble correlation on the wire). Generated by the host, or
	// client-supplied and validated there.
	ID string
	// Text is the prompt the drained turn runs.
	Text string
	// Kind decides eviction, batching and presentation.
	Kind Kind
	// Images carries user-attached images (User items only; nil otherwise).
	Images []llm.ImageInput
	// Tag is the host's per-item payload — the web host stores the delivery
	// source, the TUI the child handle of a targeted delivery. Opaque here.
	Tag any
}

// Queue is one session's FIFO. The zero value is not usable; call New.
type Queue struct {
	items []Item
	// maxUser caps User items; an insert past it is REFUSED.
	maxUser int
	// maxSystem caps Notice+Reply items; an insert past it evicts the
	// oldest Notice, or is refused when every system slot holds a Reply.
	maxSystem int
}

// New returns an empty queue with the given caps. A non-positive cap is
// treated as unbounded for that kind (tests and hosts that do not bound).
func New(maxUser, maxSystem int) *Queue {
	return &Queue{maxUser: maxUser, maxSystem: maxSystem}
}

// Len reports how many items are queued.
func (q *Queue) Len() int {
	if q == nil {
		return 0
	}
	return len(q.items)
}

// Items returns a COPY of the queue contents, for iteration and for building
// wire snapshots. Mutating the returned slice does not affect the queue.
func (q *Queue) Items() []Item {
	if q == nil || len(q.items) == 0 {
		return nil
	}
	out := make([]Item, len(q.items))
	copy(out, q.items)
	return out
}

// Peek returns the head item without removing it.
func (q *Queue) Peek() (Item, bool) {
	if q == nil || len(q.items) == 0 {
		return Item{}, false
	}
	return q.items[0], true
}

// Count reports how many queued items have the given kind.
func (q *Queue) Count(kind Kind) int {
	if q == nil {
		return 0
	}
	n := 0
	for _, it := range q.items {
		if it.Kind == kind {
			n++
		}
	}
	return n
}

// CountTag reports how many queued items carry tag.
func (q *Queue) CountTag(tag any) int {
	if q == nil {
		return 0
	}
	n := 0
	for _, it := range q.items {
		if it.Tag == tag {
			n++
		}
	}
	return n
}

// Has reports whether an item with id and the given kind is queued, so a host
// can reject or replace a duplicate client-supplied id.
func (q *Queue) Has(id string, kind Kind) bool {
	if q == nil {
		return false
	}
	for _, it := range q.items {
		if it.ID == id && it.Kind == kind {
			return true
		}
	}
	return false
}

// Outcome is what Append did with an item.
type Outcome int

const (
	// Accepted: the item is queued. Evicted is set when something had to be
	// dropped to make room (the caller reports it).
	Accepted Outcome = iota
	// Refused: the item was not queued and the caller must report an
	// actionable error. A targeted Reply arriving at a queue full of replies
	// is the case that matters: the parent is waiting on an answer, so the
	// sender (the model) is told to retry rather than the message vanishing.
	Refused
	// Dropped: the item itself was discarded. A one-way Notice arriving at a
	// queue full of replies is the case that matters — the replies must not be
	// evicted, and a notice is stale news anyway, so it is dropped and the
	// caller reports a drop.
	Dropped
)

// Append queues it, applying the kind's cap policy. The second result is the
// item the policy evicted to make room (nil when nothing was evicted).
//
// The two caps are independent: User items never evict or get evicted by
// system ones, so a flood of job notices cannot push out the user's typed text
// and vice versa.
//
// At the system cap the OLDEST NOTICE is evicted first, for either kind of
// arriving item. Only when every system slot holds a Reply does the arriving
// item's own kind decide: a Reply is REFUSED (the caller reports it; the
// pending answers stay queued) and a Notice is DROPPED (a stale notice is
// worth less than a reply someone is waiting on).
func (q *Queue) Append(it Item) (Outcome, *Item) {
	if q == nil {
		// A queue that was never created refuses: reporting a drop is better
		// than panicking inside a delivery goroutine.
		return Refused, nil
	}
	if q.maxUser > 0 && it.Kind == User && q.Count(User) >= q.maxUser {
		return Refused, nil
	}
	if q.maxSystem > 0 && it.Kind != User && q.Count(Notice)+q.Count(Reply) >= q.maxSystem {
		victim := -1
		for i, cand := range q.items {
			if cand.Kind == Notice {
				victim = i
				break
			}
		}
		if victim < 0 {
			if it.Kind == Notice {
				return Dropped, nil
			}
			return Refused, nil
		}
		dead := q.removeAt(victim)
		q.items = append(q.items, it)
		return Accepted, &dead
	}
	q.items = append(q.items, it)
	return Accepted, nil
}

// Take removes and returns the first n items (all of them when n exceeds the
// length). The removed slots are zeroed, so a multi-MB data-URL image cannot
// stay reachable through the backing array for the lifetime of the queue.
func (q *Queue) Take(n int) []Item {
	if q == nil || n <= 0 || len(q.items) == 0 {
		return nil
	}
	n = min(n, len(q.items))
	out := make([]Item, n)
	copy(out, q.items[:n])
	clear(q.items[:n])
	q.items = q.items[n:]
	return out
}

// MaxImagesPerMessage is the most images one user message may carry. The web
// host refuses a message over it, and Batch keeps a joined run under it, so
// a turn never sends more than this many images.
const MaxImagesPerMessage = 4

// Batch returns a COPY of the contiguous head run that drains as ONE turn.
// A run of Notices shares one provider request. With joinUser (the
// join_queued setting) a run of User messages does too: several things typed
// while a turn was busy are delivered as one message, in the order they were
// typed. A joined run stops before a message whose images would take the
// total over MaxImagesPerMessage, and that message starts the next turn, so
// nothing is dropped. Without joinUser each User message is its own turn. A
// Reply is always alone, because its capture is armed per turn. The run
// stops at the first different kind, so FIFO across kinds is preserved.
func (q *Queue) Batch(joinUser bool) []Item {
	if q == nil || len(q.items) == 0 {
		return nil
	}
	n := 1
	head := q.items[0].Kind
	if head == Notice || (joinUser && head == User) {
		images := len(q.items[0].Images)
		for n < len(q.items) && q.items[n].Kind == head {
			images += len(q.items[n].Images)
			if head == User && images > MaxImagesPerMessage {
				break
			}
			n++
		}
	}
	out := make([]Item, n)
	copy(out, q.items[:n])
	return out
}

// Join merges a batch into the one prompt its turn runs: the texts in queue
// order (JoinText), and every item's images in the same order.
func Join(batch []Item) (string, []llm.ImageInput) {
	if len(batch) == 1 {
		return batch[0].Text, batch[0].Images
	}
	var images []llm.ImageInput
	for _, it := range batch {
		images = append(images, it.Images...)
	}
	return JoinText(batch), images
}

// JoinText is the text of Join: the texts in queue order, blank-line
// separated. A host whose turns carry no images uses it, so it does not drop
// what Join would return.
func JoinText(batch []Item) string {
	if len(batch) == 1 {
		return batch[0].Text
	}
	var b strings.Builder
	for i, it := range batch {
		if i > 0 {
			b.WriteString("\n\n")
		}
		b.WriteString(it.Text)
	}
	return b.String()
}

// SendNowReady reports whether a Send now request has something to deliver:
// the User item id is still queued, or, for an empty id, any User item is.
// A request with nothing to deliver must not stop the running turn.
func (q *Queue) SendNowReady(id string) bool {
	if id == "" {
		return q.Count(User) > 0
	}
	return q.Has(id, User)
}

// SendNowResult is the outcome of a Send now request. Every host shows its
// Message, so the TUI, the browser and the sidebar say the same thing.
type SendNowResult int

const (
	// SendNowRecorded: the running turn stops after its current round and
	// the queue delivers.
	SendNowRecorded SendNowResult = iota
	// SendNowIdle: no turn is running, so the queue delivers on its own.
	SendNowIdle
	// SendNowNoModelCall: the session is busy without a model turn (a
	// compaction, or a turn that is still starting). There is no round to
	// stop at.
	SendNowNoModelCall
	// SendNowReply: the running turn's output is the answer to a parent's
	// send_message. Stopping it would hand the parent an empty reply, and
	// a Reply stays 1:1 with its call.
	SendNowReply
	// SendNowNotQueued: the message already left the queue.
	SendNowNotQueued
)

// CheckSendNow is the Send now rule. busy is the host's "session is
// working" state, turn is the agent's TurnGeneration (0 = no model turn),
// replying reports an armed send_message reply, and queued is
// SendNowReady. The host reads turn before queued, then records the yield
// with RequestYieldFor(turn) only for SendNowRecorded. When that turn has
// ended in between, the result is SendNowIdle.
func CheckSendNow(busy bool, turn uint64, replying, queued bool) SendNowResult {
	switch {
	case !busy:
		return SendNowIdle
	case turn == 0:
		return SendNowNoModelCall
	case replying:
		return SendNowReply
	case !queued:
		return SendNowNotQueued
	}
	return SendNowRecorded
}

// Message is the short status line a host shows for the result.
func (r SendNowResult) Message() string {
	switch r {
	case SendNowRecorded:
		return "Sending after this round."
	case SendNowIdle:
		return "No turn is running."
	case SendNowNoModelCall:
		return "Nothing to stop yet; queued messages run next."
	case SendNowReply:
		return "This turn answers a parent; queued messages run after it."
	case SendNowNotQueued:
		return "That message already left the queue."
	}
	return ""
}

// Remove drops one item by id and kind, reporting what left the queue.
func (q *Queue) Remove(id string, kind Kind) (Item, bool) {
	if q == nil || id == "" {
		return Item{}, false
	}
	for i, it := range q.items {
		if it.ID == id && it.Kind == kind {
			return q.removeAt(i), true
		}
	}
	return Item{}, false
}

// DropKind removes every item of the given kind and returns them (the
// interrupt semantic: "stop" clears the user's own queued text while machine
// deliveries, whose loss strands the delivery machinery, are kept).
func (q *Queue) DropKind(kind Kind) []Item {
	if q == nil || len(q.items) == 0 {
		return nil
	}
	var out []Item
	kept := q.items[:0]
	for _, it := range q.items {
		if it.Kind == kind {
			out = append(out, it)
			continue
		}
		kept = append(kept, it)
	}
	clear(q.items[len(kept):])
	q.items = kept
	return out
}

// removeAt deletes index i, zeroing the vacated tail slot.
func (q *Queue) removeAt(i int) Item {
	dead := q.items[i]
	copy(q.items[i:], q.items[i+1:])
	last := len(q.items) - 1
	q.items[last] = Item{} // drop the duplicated tail reference (images)
	q.items = q.items[:last]
	return dead
}

// ForceAppend queues it without applying the caps. It exists for tests that
// need an arbitrary starting queue (and for a host reconstructing state it has
// already validated); production enqueues must use Append so the policy holds.
func (q *Queue) ForceAppend(it Item) {
	if q == nil {
		return
	}
	q.items = append(q.items, it)
}
